def read_input():
    '''Reads the whole test case; only the first INPUT_MAX bytes reach the guest'''
    global last_input
    payload = b""
    while True:
        n = read(INFD, data, INPUT_MAX)
        if n <= 0:
            break
        payload += data.raw[:n]
    last_input = payload
    return payload[:INPUT_MAX]


def write_input(payload):
    global input_addr
    if input_addr is None:
        input_addr = min(afl_renode.symbol_addresses("afl_input"))
    blob = struct.pack("<II", AFL_MAGIC, len(payload)) + payload
    monitor.Machine[sysbus_name].WriteBytes(System.Array[System.Byte](bytearray(blob)),
                                            input_addr)


excl_starts = []
excl_ends = []
prev_loc = 0
prev_pc = 0
edges_seen = set()
edges_new = []
window_ready = False
in_window = False
window_starts = set()


def gate_block(pc, size):
    '''Coverage only between user_entry and an afl_* marker.

    The block hook stays installed for the whole run: switching it on and off
    from instruction hooks (cpu.AddHook) takes effect at nondeterministic
    points, which cost ~25% stability and produced false hangs.'''
    global in_window, prev_loc, prev_pc
    if pc in afl_renode.endgame:
        if afl_renode.status is None:
            afl_renode.status = afl_renode.endgame[pc]
        in_window = False
        return
    if pc == group_op_pc:
        op_entry()
    if not in_window:
        if pc in window_starts and afl_renode.status is None:
            in_window = True
            prev_loc = prev_pc = 0
        else:
            return
    cov_block(pc, size)


def load_cov_ranges():
    if COVERAGE != "kernel":
        return
    if not os.path.isfile(COV_RANGES):
        raise IOError("AFL_RENODE_COVERAGE=kernel needs harness ranges; %s not found"
                      % COV_RANGES)
    with open(COV_RANGES) as f:
        for line in f:
            low, high = line.split()[:2]
            excl_starts.append(int(low, 16))
            excl_ends.append(int(high, 16))
    print("AFL-Renode: %d harness ranges excluded from coverage" % len(excl_starts))


def cov_block(pc, size):
    '''AFL-style edge coverage, outside the harness's own code'''
    global prev_loc, prev_pc
    if excl_starts:
        i = bisect_right(excl_starts, pc) - 1
        if i >= 0 and pc < excl_ends[i]:
            return
    cur = ((pc >> 1) * 0x9E3779B1 >> 7) & MAP_MASK
    idx = cur ^ prev_loc
    mem = afl_renode.afl_mem.contents
    mem[idx] = (mem[idx] + 1) & 0xff
    prev_loc = cur >> 1
    if EDGE_LOG is not None:
        edge = (prev_pc, pc)
        if edge not in edges_seen:
            edges_seen.add(edge)
            edges_new.append(edge)
        prev_pc = pc


def set_block_hook(hook):
    for cpu in monitor.Machine[sysbus_name].GetCPUs():
        cpu.SetHookAtBlockBegin(hook)


def setup_window():
    global window_ready
    if window_ready:
        return
    window_ready = True
    load_cov_ranges()
    starts = afl_renode.symbol_addresses("user_entry")
    if not starts:
        raise ValueError("user_entry not found: cannot open the coverage window")
    window_starts.update(a & ~1 for a in starts)


def flush_edge_log():
    if EDGE_LOG is not None and edges_new:
        with open(EDGE_LOG, "a") as f:
            for src, dst in edges_new:
                f.write("%x %x\n" % (src, dst))
        del edges_new[:]


image = []
image_pcs = []


def elf_symtab(path):
    '''(value, size, type, section index, name) of every symbol of a 32-bit
    little-endian ELF'''
    with open(path, "rb") as f:
        data = f.read()
    shoff, = struct.unpack_from("<I", data, 32)
    shentsize, shnum = struct.unpack_from("<HH", data, 46)
    shdrs = [struct.unpack_from("<10I", data, shoff + i * shentsize) for i in range(shnum)]
    for sh in shdrs:
        if sh[1] != 2:          # SHT_SYMTAB
            continue
        stroff = shdrs[sh[6]][4]  # sh_link: its string table
        for off in range(sh[4], sh[4] + sh[5], 16):
            st_name, value, size, info, _, shndx = struct.unpack_from("<IIIBBH", data, off)
            end = data.index(b"\0", stroff + st_name)
            yield (value, size, info & 0xf, shndx,
                   data[stroff + st_name:end].decode("ascii", "replace"))


def elf_symbols(path):
    '''Sorted (address, size, name) of the FUNC/OBJECT symbols of a 32-bit
    little-endian ELF, Thumb bit cleared.'''
    syms = []
    for value, size, typ, shndx, name in elf_symtab(path):
        # OBJECT/FUNC, not undefined or absolute (Kconfig values, offsets)
        if typ not in (1, 2) or not value or shndx in (0, 0xfff1):
            continue
        syms.append((value & ~1 if typ == 2 else value, size, name))
    syms.sort()
    return syms


_symbols = None


def symbols():
    '''The ELF's symbols, read once. Renode's own lookup cannot be used:
    Machine.Reset() drops the symbols and reloading them (LoadSymbolsFrom)
    leaks ~140 KB of Renode memory per call, i.e. per failure.'''
    global _symbols
    if _symbols is None:
        _symbols = elf_symbols(os.environ["AFL_RENODE_ELF"])
    return _symbols


def elf_load_ranges(path):
    '''(address, memsz) of the PT_LOAD segments of a 32-bit little-endian ELF'''
    with open(path, "rb") as f:
        ehdr = f.read(52)
        if ehdr[:4] != b"\x7fELF" or ehdr[4:6] != b"\x01\x01":
            raise ValueError("%s: not a 32-bit little-endian ELF" % path)
        phoff, = struct.unpack_from("<I", ehdr, 28)
        phentsize, phnum = struct.unpack_from("<HH", ehdr, 42)
        ranges = []
        for i in range(phnum):
            f.seek(phoff + i * phentsize)
            p_type, _, _, p_paddr, _, p_memsz = struct.unpack("<6I", f.read(24))
            if p_type == 1 and p_memsz:
                ranges.append((p_paddr, p_memsz))
    return ranges


def snapshot_image():
    '''Saves the freshly loaded ELF (with zeroed .bss) and the entry PCs.

    The resc loads the ELF once: reloading it on every reset (a "reset" macro
    running LoadELF) leaks ~175 KB of Renode memory per test case, gigabytes
    per hour per instance.'''
    elf = os.environ.get("AFL_RENODE_ELF")
    if not elf:
        raise ValueError("AFL_RENODE_ELF not set: pass the ELF to afl-renode-trace")
    bus, _ = bus_and_cpu()
    for addr, size in elf_load_ranges(elf):
        image.append((addr, bus.ReadBytes(System.UInt64(addr), size)))
    image_pcs.extend(cpu.PC for cpu in bus.GetCPUs())


def restore_image():
    bus = monitor.Machine[sysbus_name]
    for addr, blob in image:
        bus.WriteBytes(blob, System.UInt64(addr))
    for cpu, pc in zip(bus.GetCPUs(), image_pcs):
        cpu.PC = pc


def heartbeat():
    global last_beat
    now = time.time()
    if not HEARTBEAT or now - last_beat < HEARTBEAT_SECS:
        return
    last_beat = now
    with open(HEARTBEAT, "a"):
        os.utime(HEARTBEAT, None)


def do_one_child():
    global started, quanta, run_start, hang_cause
    _orig_do_one_child()
    quanta = 0
    hang_cause = None
    heartbeat()
    if not started:
        snapshot_image()
    else:
        restore_image()
    write_input(read_input())

    if COVERAGE == "all":
        # Trace from the very first block after reset, instead of waiting a quantum
        set_block_hook(afl_renode.log_basic_block)
    else:
        setup_window()
        global in_window
        in_window = False
        if group_op_pc is None:
            setup_op_hook()
        global last_op_offset
        last_op_offset = -1
        del trace[:]
        set_block_hook(gate_block)
    afl_renode.reset = False
    run_start = time.time()

    if not started:
        started = True
        if not NO_START:
            emulationManager.Instance.CurrentEmulation.StartAll()


def quantum_hook(mach):
    global quanta, hang_cause
    quanta += 1
    if afl_renode.status is not None:
        return
    if quanta > MAX_QUANTA:
        hang_cause = "%d quanta" % MAX_QUANTA
    elif MAX_WALL > 0 and time.time() - run_start > MAX_WALL:
        hang_cause = "%g s wall clock, %d quanta" % (MAX_WALL, quanta)
    if hang_cause:
        afl_renode.status = STATUS_HANG


group_op_pc = None
last_op_offset = -1
rewinds = 0
trace = []
trace_info = {}


def setup_op_hook():
    global group_op_pc
    group_op_pc = -1    # not a syscall harness ELF: no hook
    syms = dict((n, a) for a, _, n in symbols())
    if "group_op" in syms and "fz_mem" in syms:
        trace_info.update(fz_mem=syms["fz_mem"], kernel=syms.get("_kernel"))
        group_op_pc = syms["group_op"]
    if TRACE:
        setup_trace()


def op_entry():
    '''At group_op entry: main.c has just stored the op's offset and byte.

    The input offset of successive ops only grows. If it goes back, a
    syscall overwrote the stream position (the guest keeps raw pointers off
    it, so this is a harness bug): the input would replay in a loop until
    the run budget, so end the run here like the guest's own tamper check,
    and log the input.'''
    global last_op_offset, rewinds
    bus = monitor.Machine[sysbus_name]
    offset = int(bus.ReadDoubleWord(System.UInt64(trace_info["fz_mem"] + 8)))
    if offset <= last_op_offset:
        rewinds += 1
        if not TRACE and afl_renode.status is None:
            afl_renode.status = STATUS_SUCCESS
            if CRASH_INFO_DIR:
                with open(os.path.join(CRASH_INFO_DIR, "rewinds.log"), "a") as f:
                    f.write("%s\n" % hashlib.sha1(last_input).hexdigest())
    last_op_offset = offset
    if TRACE:
        trace_op(offset)


def setup_trace():
    '''Finds the group (from its Kconfig symbol) and its op names (the enum
    in src/group_<name>.c).'''
    elf = os.environ["AFL_RENODE_ELF"]
    conf = dict((n, v) for v, _, _, shndx, n in elf_symtab(elf)
                if shndx == 0xfff1 and n.startswith("CONFIG_"))
    groups = [n[len("CONFIG_SYSCALL_FUZZ_GROUP_"):].lower() for n in conf
              if n.startswith("CONFIG_SYSCALL_FUZZ_GROUP_")]
    if len(groups) != 1:
        raise ValueError("AFL_RENODE_TRACE: cannot tell the group of %s" % elf)
    names = []
    with open(os.path.join(SRC_DIR, "group_%s.c" % groups[0])) as f:
        src = f.read()
    m = re.search(r"enum (?:fz_)?op \{([^}]*)\}", src)
    if m:
        names = [n.strip()[3:] for n in m.group(1).split(",") if n.strip()]
    names = names[:names.index("COUNT")] if "COUNT" in names else names
    syms = dict((n, (a, size)) for a, size, n in symbols())
    workers, size = syms["workers"]
    nworkers = conf.get("CONFIG_SYSCALL_FUZZ_WORKERS", 2)
    trace_info.update(group=groups[0], names=names, workers=workers,
                      thread_size=size // nworkers, nworkers=nworkers)


def trace_op(offset):
    bus = monitor.Machine[sysbus_name]
    op = bus.ReadByte(System.UInt64(trace_info["fz_mem"] + 12))  # fz_mem.cur_op
    cur = bus.ReadDoubleWord(System.UInt64(trace_info["kernel"] + 8))  # _kernel.cpus[0].current
    trace.append((offset, int(op), int(cur), quanta))


def thread_name(addr):
    i, rem = divmod(addr - trace_info["workers"], trace_info["thread_size"])
    if rem == 0 and 0 <= i < trace_info["nworkers"]:
        return "w%d" % i
    return symbolize(addr)


def write_trace(status):
    names = trace_info["names"]
    lines = ["# group %s, %d bytes, sha1 %s" % (trace_info["group"], len(last_input),
                                               hashlib.sha1(last_input).hexdigest()),
             "# arguments are the bytes up to the next op, in execution order",
             "# offset  quantum  worker  op",
             ]
    n = sum(1 for a, b in zip(trace, trace[1:]) if b[0] <= a[0])
    if n:
        lines.append("# stream rewound %d times: a syscall overwrote the workers' "
                     "input position (harness artefact)" % n)
    for i, (offset, op, cur, q) in enumerate(trace):
        if TRACE_KEEP <= i < len(trace) - TRACE_KEEP:
            if i == TRACE_KEEP:
                lines.append("# ... %d ops left out ..." % (len(trace) - 2 * TRACE_KEEP))
            continue
        end = trace[i + 1][0] if i + 1 < len(trace) else len(last_input)
        if end <= offset:
            end = len(last_input)
        name = names[op % len(names)] if names else "?"
        args = " ".join("%02x" % b for b in bytearray(last_input[offset + 1:end]))
        lines.append("%8d %8d  %-6s  %#04x %-16s %s" % (offset, q, thread_name(cur),
                                                          op, name, args))
    lines.append("# outcome:")
    if status == STATUS_SUCCESS:
        lines.append("status: 0 (done)")
    else:
        lines.extend(describe_failure(status))
    with open(TRACE, "w") as f:
        f.write("\n".join(lines) + "\n")
    del trace[:]


def bus_and_cpu():
    bus = monitor.Machine[sysbus_name]
    return bus, list(bus.GetCPUs())[0]


def symbolize(addr):
    syms = symbols()
    a = addr & ~1
    i = bisect_right(syms, (a, 0xFFFFFFFF, "")) - 1
    # the closest preceding symbols that contain a (sizes may overlap)
    while i >= 0 and syms[i][0] > a - 0x10000:
        start, size, name = syms[i]
        if a < start + max(size, 1):
            return "%s (%s+%#x)" % (hex(addr), name, a - start)
        i -= 1
    return hex(addr)


def read_string(addr, limit=256):
    bus, _ = bus_and_cpu()
    raw = bytes(bytearray(bus.ReadBytes(System.UInt64(addr), limit)))
    return raw.split(b"\0", 1)[0].decode("ascii", "replace")


def describe_failure(status):
    lines = ["status: %d (%s)" % (status, {STATUS_ABORT: "bug", STATUS_HANG: "hang"}
                                           .get(status, "other")),
             "input: %d bytes, sha1 %s" % (len(last_input),
                                           hashlib.sha1(last_input).hexdigest())]
    if status == STATUS_HANG and hang_cause:
        lines.append("hang: %s" % hang_cause)
    addrs = [a for a, _, n in symbols() if n == "afl_crash"]
    if not addrs:
        return lines + ["no afl_crash symbol in this ELF"]
    bus, _ = bus_and_cpu()
    raw = bytes(bytearray(bus.ReadBytes(System.UInt64(min(addrs)), 4 * len(CRASH_FIELDS))))
    rec = dict(zip(CRASH_FIELDS, struct.unpack("<%dI" % len(CRASH_FIELDS), raw)))
    if rec["magic"] != AFL_CRASH_MAGIC:
        return lines + ["no guest crash record (host watchdog or crash before main)"]
    lines.append("reason: %d (%s)" % (rec["reason"], REASONS.get(rec["reason"], "?")))
    lines.append("thread: %s" % symbolize(rec["thread"]))
    if rec["esf_valid"]:
        lines.append("pc: %s" % symbolize(rec["pc"]))
        lines.append("lr: %s" % symbolize(rec["lr"]))
        lines.append("r0-r3: %s  r12: %#x" % (
            " ".join("%#x" % rec[r] for r in ("r0", "r1", "r2", "r3")), rec["r12"]))
        lines.append("xpsr: %#x (mode %s)" % (rec["xpsr"], ARM_MODES.get(rec["xpsr"] & 0x1f, "?")))
    if rec["reason"] not in (2, 3, 4, 0xFFFFFFFF):
        lines.append("dfsr: %#x dfar: %#x ifsr: %#x ifar: %#x" % (
            rec["dfsr"], rec["dfar"], rec["ifsr"], rec["ifar"]))
    if rec["assert_file"]:
        lines.append("assert: %s:%d" % (read_string(rec["assert_file"]), rec["assert_line"]))
    lines.append("last op: %#x at input offset %d" % (rec["op"], rec["op_offset"]))
    return lines


def one_fuzz_complete(status):
    global held
    if held:
        return
    flush_edge_log()
    if TRACE and group_op_pc not in (None, -1):
        write_trace(status)
    if status != STATUS_SUCCESS:
        text = "\n".join(describe_failure(status)) + "\n"
        if afl_renode.shmid == -1:
            print("AFL-Renode crash info:\n" + text)
        if CRASH_INFO_DIR:
            name = hashlib.sha1(last_input).hexdigest() + ".txt"
            with open(os.path.join(CRASH_INFO_DIR, name), "w") as f:
                f.write(text)
        if HOLD:
            held = True
            print("AFL-Renode: holding the machine for the debugger")
            return
    _orig_one_fuzz_complete(status)


